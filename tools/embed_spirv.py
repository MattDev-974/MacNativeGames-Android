#!/usr/bin/env python3
"""Turn compiled .spv files into a C header (uint32_t arrays, no libstdc++)."""
import sys, struct, pathlib

def emit(path: pathlib.Path, name: str, out):
    data = path.read_bytes()
    if len(data) % 4:
        sys.exit(f"{path}: size {len(data)} is not a multiple of 4")
    words = struct.unpack(f"<{len(data)//4}I", data)
    out.write(f"/* generated from {path.name} - do not edit */\n")
    out.write(f"static const uint32_t {name}[] = {{\n")
    for i in range(0, len(words), 8):
        out.write("    " + ", ".join(f"0x{w:08x}u" for w in words[i:i+8]) + ",\n")
    out.write("};\n")
    # VkShaderModuleCreateInfo.codeSize is in BYTES, not in words.  Emitting the
    # word count here truncates the module to a quarter and crashes Mali's
    # compiler inside vkCreateGraphicsPipelines.
    out.write(f"static const uint32_t {name}_words = {len(words)};   /* for checks */\n")
    out.write(f"static const uint32_t {name}_len = {len(data)};   /* bytes */\n\n")

def main():
    if len(sys.argv) < 3:
        sys.exit("usage: embed_spirv.py <header-out> <name>=<file.spv> ...")
    out_path = pathlib.Path(sys.argv[1])
    chunks = []
    import io
    buf = io.StringIO()
    buf.write("/* Generated by tools/embed_spirv.py - do not edit. */\n")
    buf.write("#pragma once\n#include <stdint.h>\n\n")
    for spec in sys.argv[2:]:
        name, _, f = spec.partition("=")
        emit(pathlib.Path(f), name, buf)
    out_path.write_text(buf.getvalue())
    print(f"wrote {out_path}")

main()
